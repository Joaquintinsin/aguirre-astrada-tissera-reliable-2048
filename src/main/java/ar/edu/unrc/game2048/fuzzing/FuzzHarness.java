package ar.edu.unrc.game2048.fuzzing;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Random;

import ar.edu.unrc.game2048.Board;
import ar.edu.unrc.game2048.DeterministicPlacement;

/**
 * Fuzzing harness for Board.fromString and the moves (Assignment 5, Ej. 1.a).
 *
 * Reads a file with one board per line (produced by
 * fuzzing/grammar_fuzzer.py). Everything runs in a single JVM, so thousands
 * of boards are checked in seconds.
 *
 * Outcomes per input:
 *   PASS  - every oracle held
 *   FAIL  - an oracle was violated (wrong result, no exception)
 *   CRASH - an unexpected exception/error escaped (includes AssertionError)
 *
 * Usage:
 *   java -ea -cp target/classes ar.edu.unrc.game2048.fuzzing.FuzzHarness \
 *        boards.txt [movesPerBoard] [seed] [failuresReport.tsv]
 */
public class FuzzHarness {

    enum Outcome { PASS, FAIL, CRASH }

    /** Result of checking one input. */
    static final class Result {
        final Outcome outcome;
        final String signature;   // groups failures with the same cause
        final String detail;

        Result(Outcome outcome, String signature, String detail) {
            this.outcome = outcome;
            this.signature = signature;
            this.detail = detail;
        }

        static final Result PASS = new Result(Outcome.PASS, "", "");

        static Result fail(String signature, String detail) {
            return new Result(Outcome.FAIL, signature, detail);
        }

        static Result crash(Throwable t, String detail) {
            StackTraceElement where = t.getStackTrace().length > 0 ? t.getStackTrace()[0] : null;
            String sig = t.getClass().getSimpleName() + " at " + where;
            return new Result(Outcome.CRASH, sig, detail + " -> " + t);
        }
    }

    private static final char[] MOVES = { 'W', 'A', 'S', 'D' };

    private final int movesPerBoard;
    private final long seed;

    FuzzHarness(int movesPerBoard, long seed) {
        this.movesPerBoard = movesPerBoard;
        this.seed = seed;
    }

    Result check(String input, int index) {
        // Oracle 1: a board generated by the grammar is accepted
        Board board;
        try {
            board = Board.fromString(input, new DeterministicPlacement());
        } catch (IllegalArgumentException e) {
            return Result.fail("rejected a valid board", e.getMessage());
        } catch (Throwable t) {
            return Result.crash(t, "fromString");
        }

        // Oracle 2: representation invariant right after parsing
        if (!board.repOk()) {
            return Result.fail("repOk false after fromString", board.toArrayString());
        }

        // Oracle 3: round trip  fromString -> toArrayString == input
        if (!board.toArrayString().equals(input)) {
            return Result.fail("round trip mismatch",
                    "expected " + input + " got " + board.toArrayString());
        }

        // Oracles 4..: random moves compared against a reference model
        ReferenceModel model = ReferenceModel.of(board);
        Random rnd = new Random(seed + index);
        StringBuilder played = new StringBuilder();

        for (int i = 0; i < movesPerBoard; i++) {
            char move = MOVES[rnd.nextInt(MOVES.length)];
            played.append(move);
            String context = "moves=" + played + " before=" + model;

            boolean moved;
            try {
                moved = apply(board, move);
            } catch (Throwable t) {
                return Result.crash(t, context);
            }
            boolean expectedMoved = model.move(move);

            if (!board.repOk()) {
                return Result.fail("repOk false after move", context + " after=" + board.toArrayString()
                        + " score=" + board.getScore());
            }
            if (board.getScore() < 0) {
                return Result.fail("negative score", context + " score=" + board.getScore());
            }
            if (moved != expectedMoved) {
                return Result.fail("move() returned " + moved + " but expected " + expectedMoved, context);
            }
            if (!model.sameAs(board)) {
                return Result.fail("board differs from reference model",
                        context + " expected=" + model + " got=" + board.toArrayString()
                                + " score=" + board.getScore());
            }
        }
        return Result.PASS;
    }

    private static boolean apply(Board b, char move) {
        switch (move) {
            case 'W': return b.moveUp();
            case 'S': return b.moveDown();
            case 'A': return b.moveLeft();
            case 'D': return b.moveRight();
            default: throw new IllegalStateException("unknown move " + move);
        }
    }

    // ============================ DRIVER ============================

    public static void main(String[] args) throws IOException {
        if (args.length < 1) {
            System.err.println("Usage: FuzzHarness <boards.txt> [movesPerBoard] [seed] [report.tsv]");
            System.exit(2);
        }
        String inputFile = args[0];
        int moves = args.length > 1 ? Integer.parseInt(args[1]) : 20;
        long seed = args.length > 2 ? Long.parseLong(args[2]) : 0L;
        String reportFile = args.length > 3 ? args[3] : null;

        FuzzHarness harness = new FuzzHarness(moves, seed);
        List<String> lines = Files.readAllLines(Paths.get(inputFile), StandardCharsets.UTF_8);

        int[] counts = new int[Outcome.values().length];
        int total = 0;
        // signature -> [count, first example]
        Map<String, Object[]> bySignature = new LinkedHashMap<>();
        List<String> report = new ArrayList<>();
        report.add("line\toutcome\tsignature\tinput\tdetail");

        for (int i = 0; i < lines.size(); i++) {
            String input = lines.get(i);
            if (input.isEmpty()) {
                continue;
            }
            total++;
            Result r = harness.check(input, i);
            counts[r.outcome.ordinal()]++;

            if (r.outcome != Outcome.PASS) {
                String key = r.outcome + ": " + r.signature;
                Object[] entry = bySignature.get(key);
                if (entry == null) {
                    bySignature.put(key, new Object[] { 1, "line " + (i + 1) + ": " + input + "\n      " + r.detail });
                } else {
                    entry[0] = (Integer) entry[0] + 1;
                }
                report.add((i + 1) + "\t" + r.outcome + "\t" + r.signature + "\t" + input + "\t" + r.detail);
            }
        }

        System.out.println("=== FuzzHarness: " + inputFile + " ===");
        System.out.println("boards: " + total + ", moves per board: " + moves);
        for (Outcome o : Outcome.values()) {
            System.out.println(o + ": " + counts[o.ordinal()]);
        }
        if (!bySignature.isEmpty()) {
            System.out.println();
            System.out.println("Distinct failure signatures (count, first example):");
            for (Map.Entry<String, Object[]> e : bySignature.entrySet()) {
                System.out.println("[" + e.getValue()[0] + "] " + e.getKey());
                System.out.println("      " + e.getValue()[1]);
            }
        }
        if (reportFile != null) {
            try (PrintWriter pw = new PrintWriter(reportFile, "UTF-8")) {
                for (String l : report) {
                    pw.println(l);
                }
            }
            System.out.println();
            System.out.println("Full report: " + reportFile);
        }
        System.exit(counts[Outcome.PASS.ordinal()] == total ? 0 : 1);
    }
}
